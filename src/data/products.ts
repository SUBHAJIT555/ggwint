export function toCategorySlug(category: string) {
  return category
    .toLowerCase()
    .replace(/\s*\/\s*/g, "-")
    .replace(/ & /g, "-")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

